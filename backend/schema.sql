    ON security_events(destination_ip);

CREATE INDEX idx_alerts_alert_type
    ON alerts(alert_type);

CREATE INDEX idx_alerts_status
    ON alerts(status);

CREATE INDEX idx_alerts_severity
    ON alerts(severity);

CREATE INDEX idx_alerts_source_ip
    ON alerts(source_ip);

CREATE INDEX idx_alerts_destination_ip
    ON alerts(destination_ip);

CREATE INDEX idx_alerts_asset_id
    ON alerts(asset_id);

CREATE INDEX idx_alerts_last_seen
    ON alerts(last_seen);

-- Prevent duplicate OPEN alerts for the same
-- detection type and source/destination pair.
CREATE UNIQUE INDEX uq_open_alert_source_destination
    ON alerts (
        alert_type,
        source_ip,
        destination_ip
    )
    WHERE status = 'OPEN';


-- ==========================================
-- PHASE 12: CORRELATION ENGINE
-- ==========================================

-- Links an existing SOC alert with an existing
-- vulnerability/service vulnerability on the same asset.
CREATE TABLE IF NOT EXISTS correlations (
    id BIGSERIAL PRIMARY KEY,

    asset_id BIGINT NOT NULL
        REFERENCES assets(id)
        ON DELETE CASCADE,

    alert_id BIGINT NOT NULL
        REFERENCES alerts(id)
        ON DELETE CASCADE,

    service_vulnerability_id BIGINT
        REFERENCES service_vulnerabilities(id)
        ON DELETE SET NULL,

    finding_id BIGINT,

    correlation_type TEXT NOT NULL
        CHECK (
            correlation_type IN (
                'ASSET_VULNERABILITY_ALERT'
            )
        ),

    priority TEXT NOT NULL
        CHECK (
            priority IN (
                'CRITICAL',
                'HIGH',
                'MEDIUM',
                'LOW',
                'INFO'
            )
        ),

    title TEXT NOT NULL,

    description TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ==========================================
-- CORRELATION INDEXES
-- ==========================================

CREATE INDEX IF NOT EXISTS idx_correlations_asset_id
    ON correlations(asset_id);

CREATE INDEX IF NOT EXISTS idx_correlations_alert_id
    ON correlations(alert_id);

CREATE INDEX IF NOT EXISTS idx_correlations_service_vulnerability_id
    ON correlations(service_vulnerability_id);

CREATE INDEX IF NOT EXISTS idx_correlations_finding_id
    ON correlations(finding_id);

CREATE INDEX IF NOT EXISTS idx_correlations_priority
    ON correlations(priority);

CREATE INDEX IF NOT EXISTS idx_correlations_created_at
    ON correlations(created_at);

-- Prevent the same alert and service vulnerability
-- from producing duplicate correlation records.
CREATE UNIQUE INDEX IF NOT EXISTS uq_correlations_alert_vulnerability
    ON correlations(
        alert_id,
        service_vulnerability_id
    );